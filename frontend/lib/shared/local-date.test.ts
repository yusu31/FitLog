import { toLocalDate } from './local-date';

// 日本時間（Asia/Tokyo）の日付の計算（docs/testing-design.md 3-3 の T-DATE-01〜06・11）。
// 2026-10-25 は日曜、2026-10-26 は月曜。画面と API が同じ結果を出す「共通の関数」の単体テスト。
describe('toLocalDate（UTC の時刻 → 日本時間の日付）', () => {
  it.each<[string, string, string]>([
    ['T-DATE-01 日曜 23:59:59（日本）', '2026-10-25T14:59:59Z', '2026-10-25'],
    ['T-DATE-02 月曜 0:00:00（日本）', '2026-10-25T15:00:00Z', '2026-10-26'],
    ['T-DATE-03 UTC では日曜、日本では月曜', '2026-10-25T23:30:00Z', '2026-10-26'],
    ['T-DATE-04 UTC と日本で日付が同じ', '2026-10-26T03:00:00Z', '2026-10-26'],
    ['T-DATE-05 年またぎ（日本時間の1月1日 0:00）', '2026-12-31T15:00:00Z', '2027-01-01'],
    ['T-DATE-05 年またぎの直前（日本時間の12月31日 23:59:59）', '2026-12-31T14:59:59Z', '2026-12-31'],
    ['T-DATE-06 うるう日の終わり', '2028-02-29T14:59:59Z', '2028-02-29'],
    ['T-DATE-06 うるう日の翌日の始まり', '2028-02-29T15:00:00Z', '2028-03-01'],
  ])('%s', (_name, utc, expected) => {
    expect(toLocalDate(new Date(utc))).toBe(expected);
  });

  // T-DATE-11: 端末（や送られた文字列）のタイムゾーンに関係なく、同じ瞬間なら同じ日付
  it('同じ瞬間なら、どのタイムゾーンの表記で書いても同じ日付になる', () => {
    const instant = '2026-10-26T00:00:00+09:00'; // 日本時間の月曜 0:00
    expect(toLocalDate(new Date(instant))).toBe('2026-10-26');
    expect(toLocalDate(new Date('2026-10-25T15:00:00Z'))).toBe('2026-10-26');
    expect(toLocalDate(new Date('2026-10-25T10:00:00-05:00'))).toBe('2026-10-26'); // 米国東部の日曜 10:00 ＝ 日本の月曜 0:00
  });

  it('1桁の月・日は 0 を付けて YYYY-MM-DD にする', () => {
    expect(toLocalDate(new Date('2026-01-04T00:00:00Z'))).toBe('2026-01-04');
  });
});
